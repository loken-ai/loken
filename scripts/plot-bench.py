#!/usr/bin/env python3
"""Render the benchmark results as a local interactive scatter plot.

Written beside the markdown report and regenerated by the same cell that writes a row,
so the plot never lags the table. Self-contained: the measurements are embedded, so the
file opens from disk with no server and no network.
"""
import json, glob, os, sys, datetime, pathlib

# Derived from where this script sits, so it renders the same tree whatever the caller's
# working directory is.
ROOT = pathlib.Path(__file__).resolve().parent.parent
RESULTS = sys.argv[1] if len(sys.argv) > 1 else str(ROOT / "results")
OUT = sys.argv[2] if len(sys.argv) > 2 else str(ROOT / "docs" / "bench.html")

rows = []
for p in sorted(glob.glob(os.path.join(RESULTS, "*.json"))):
    j = json.load(open(p))
    when = datetime.datetime.fromtimestamp(os.stat(p).st_mtime).strftime("%Y-%m-%d %H:%M")
    dev = "CPU" if p.endswith("_cpu.json") else "GPU"
    for r in j.get("results", []):
        st = r.get("stats", {})
        if "Completion tok/s" not in st:
            continue
        rows.append(dict(
            model=r["model"], target=r["target"], ctx=r.get("num_ctx", 4096),
            prompt=r.get("prompt", "short"), device=dev,
            decode=round(st["Completion tok/s"]["mean"], 1),
            prefill=round(st.get("Prompt tok/s", {}).get("mean", 0), 1),
            tokens=round(st["Tokens generated"]["mean"]),
            e2e=round(st["E2E latency"]["mean"]),
            jtok=round(st.get("Energy J/tok", {}).get("mean", 0), 3),
            when=when))

